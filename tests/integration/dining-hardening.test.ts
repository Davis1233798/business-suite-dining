test("Dining: concurrent ordering/payment/reservation remain atomic and tenant scoped", async () => {
  const sessionId = crypto.randomUUID();
  const org = `org_${sessionId}`;
  await seedOrganization(org);
  const db = getDb();
  const context = {organizationId: org, userId: "tester", userEmail: "tester@test.local", userDisplayName: "Test", role: "admin" as const, requestId: crypto.randomUUID()};
  const token = `token_tbl_a2_${org}`;
  const input = {sessionToken: token, items: [{menuItemId: `din_menu_02_${org}`, quantity: 1}], idempotencyKey: "same-order"};
  const results = await Promise.all([DiningService.placeOrder(context, input), DiningService.placeOrder(context, input)]);
  assert.equal(results[0].orderId, results[1].orderId);
  const orders = await db.select().from(diningOrders).where(and(eq(diningOrders.organizationId, org), eq(diningOrders.idempotencyKey, "same-order")));
  assert.equal(orders.length, 1);
  await assert.rejects(DiningService.placeOrder(context, {...input, items: [{menuItemId: `din_menu_02_${org}`, quantity: 2}]}), /相同重送識別碼/);
  await assert.rejects(DiningService.placeOrder(context, {...input, idempotencyKey: "negative", items: [{menuItemId: `din_menu_02_${org}`, quantity: -1}]}), /數量/);
  await assert.rejects(DiningService.placeOrder({...context, role: "readonly"}, input), /唯讀/);
  await assert.rejects(DiningService.placeOrder(context, {sessionToken: token, items: [{menuItemId: `din_menu_03_${org}`, quantity: 1, modifiers: [{groupId: `din_modg_01_${org}`, optionId: "foreign-option"}]}]}), /規格不存在/);
  const billInput = {sessionId: `din_sess_a2_${org}`, splits: [{splitIndex: 1, amount: 682, paymentMethod: "cash"}]};
  const paid = await Promise.allSettled([DiningService.splitAndPayBill(context, billInput), DiningService.splitAndPayBill(context, billInput)]);
  assert.equal(paid.filter(p => p.status === "fulfilled").length, 1);
  assert.equal((await db.select().from(diningBills).where(eq(diningBills.organizationId, org))).length, 1);
  const [closed] = await db.select().from(diningTableSessions).where(eq(diningTableSessions.id, billInput.sessionId));
  assert.equal(closed.status, "closed");
  const [item] = await db.select().from(diningOrderItems).where(eq(diningOrderItems.orderId, orders[0].id));
  await assert.rejects(DiningService.cancelOrderItem(context, {orderItemId: item.id, reason: "after payment"}));
  const reservation = {tableId: `din_tbl_a1_${org}`, customerName: "Customer", customerPhone: "0900000000", guestCount: 2, reservationTime: "2026-11-05T10:00:00.000Z"};
  const reserved = await Promise.allSettled([DiningService.reserveTable(context, reservation), DiningService.reserveTable(context, reservation)]);
  assert.equal(reserved.filter(r => r.status === "fulfilled").length, 1);
  assert.equal((await db.select().from(diningReservations).where(eq(diningReservations.organizationId, org))).length, 1);

  const request = () => new NextRequest("http://localhost/api/dining/session", {method: "POST", headers: {cookie: `demo_session_id=${sessionId}`, "content-type": "application/json"}, body: JSON.stringify({tableId: reservation.tableId, guestCount: 2})});
  const opened = await Promise.all([openTable(request()), openTable(request())]);
  assert.equal(opened.filter(r => r.status === 200).length, 1, JSON.stringify(await Promise.all(opened.map(r => r.clone().json()))));
  const active = await db.select().from(diningTableSessions).where(and(eq(diningTableSessions.organizationId, org), eq(diningTableSessions.tableId, reservation.tableId), eq(diningTableSessions.status, "active")));
  assert.equal(active.length, 1);
});

test("Dining: prepaid takeout, urgent KDS, refund net revenue and 90 minute bookings", async () => {
  const org = `dining_takeout_${crypto.randomUUID()}`;
  await seedOrganization(org);
  const context = {organizationId: org, userId: "tester", userEmail: "tester@test.local", userDisplayName: "Test", role: "admin" as const, requestId: crypto.randomUUID()};
  const db = getDb();
  const input = {sessionToken: "", orderType: "takeout" as const, paymentMethod: "mock_card" as const, items: [{menuItemId: `din_menu_02_${org}`, quantity: 2}], idempotencyKey: "takeout-same"};
  const placed = await Promise.all([DiningService.placeOrder(context, input), DiningService.placeOrder(context, input)]);
  assert.equal(placed[0].orderId, placed[1].orderId);
  assert.ok(placed[0].takeoutNumber);
  assert.equal(placed[0].finalAmount, 640);
  assert.equal(placed[0].serviceCharge, 0);
  const [bill] = await db.select().from(diningBills).where(eq(diningBills.orderId, placed[0].orderId));
  assert.equal(bill.sessionId, null);
  assert.equal(bill.paidAmount, 640);
  const [ticket] = await db.select().from(diningKitchenTickets).where(eq(diningKitchenTickets.orderId, placed[0].orderId));
  await assert.rejects(DiningService.urgeKitchenTicket({...context, organizationId: "foreign"}, {ticketId: ticket.id}), /不存在/);
  await DiningService.urgeKitchenTicket(context, {ticketId: ticket.id});
  assert.equal((await db.select().from(diningKitchenTickets).where(eq(diningKitchenTickets.id, ticket.id)))[0].urgentFlag, true);
  for (const status of ["cooking", "done", "served"] as const) await DiningService.updateKdsTicketStatus(context, {ticketId: ticket.id, newStatus: status});
  assert.equal((await db.select().from(diningOrders).where(eq(diningOrders.id, placed[0].orderId)))[0].status, "completed");
  assert.equal((await db.select().from(diningBills).where(eq(diningBills.id, bill.id)))[0].status, "paid");
  const joinCheck = await db.select().from(diningBills).innerJoin(diningOrders, eq(diningOrders.id, diningBills.orderId)).where(eq(diningOrders.id, placed[0].orderId));
  assert.equal(joinCheck[0]?.dining_bills.status, "paid", JSON.stringify(joinCheck));
  await assert.rejects(DiningService.refundTakeout({...context, role: "operator"}, {orderId: placed[0].orderId, reason: "Refund"}), /管理員/);
  const refunds = await Promise.allSettled([DiningService.refundTakeout(context, {orderId: placed[0].orderId, reason: "Customer cancelled"}), DiningService.refundTakeout(context, {orderId: placed[0].orderId, reason: "Customer cancelled"})]);
  assert.equal(refunds.filter(r => r.status === "fulfilled").length, 1, refunds.map(r => r.status === "rejected" ? `${r.reason.message}: ${r.reason.cause?.message}` : "ok").join("; "));
  const payments = await db.select().from(diningPayments).where(eq(diningPayments.billId, bill.id));
  assert.equal(payments.length, 2);
  assert.equal(payments.reduce((sum, p) => sum + p.amount, 0), 0);
  assert.equal((await db.select().from(diningBills).where(eq(diningBills.id, bill.id)))[0].paidAmount, 0);
  const another = await DiningService.placeOrder(context, {...input, idempotencyKey: "takeout-another"});
  assert.notEqual(another.takeoutNumber, placed[0].takeoutNumber);
  const booking = {tableId: `din_tbl_b1_${org}`, customerName: "Test", customerPhone: "0900000000", guestCount: 2, reservationTime: "2026-11-06T10:00:00Z"};
  await DiningService.reserveTable(context, booking);
  await assert.rejects(DiningService.reserveTable(context, {...booking, reservationTime: "2026-11-06T10:45:00Z"}), /已有預約/);
  await DiningService.reserveTable(context, {...booking, reservationTime: "2026-11-06T11:30:00Z"});
});
